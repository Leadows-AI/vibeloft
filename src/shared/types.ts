// Data model shared by the main process and the UI.

export type ProjectKind = 'web' | 'mobile' | 'other'
export type ProjectStatus = 'active' | 'paused' | 'delivered'

export interface Customer {
  id: string
  name: string
  contact?: string
  notes?: string
}

export interface Project {
  id: string
  name: string
  customerId: string | null
  kind: ProjectKind
  status: ProjectStatus
  /** Set when archived: hidden from the sidebar, dashboard and search until restored. */
  archivedAt?: string | null
  description: string
  localPath: string | null
  /** GitHub "owner/name" */
  repo: string | null
  techStack: string[]
  /** Markdown, usually generated by Claude */
  architecture: string
  architectureUpdatedAt: string | null
  claudeSessionId: string | null
  lastSyncedAt: string | null
  createdAt: string
}

export type WorkKind = 'feature' | 'bug'
export type WorkStatus = 'backlog' | 'todo' | 'in_progress' | 'review' | 'done'
export type Priority = 'low' | 'medium' | 'high' | 'critical'

export const WORK_STATUSES: { id: WorkStatus; label: string }[] = [
  { id: 'backlog', label: 'Backlog' },
  { id: 'todo', label: 'To do' },
  { id: 'in_progress', label: 'In progress' },
  { id: 'review', label: 'Review' },
  { id: 'done', label: 'Done' }
]

export interface WorkItem {
  id: string
  projectId: string
  kind: WorkKind
  title: string
  body: string
  status: WorkStatus
  priority: Priority
  milestoneId: string | null
  /** GitHub logins; missing on items from before assignees synced */
  assignees?: string[]
  githubNumber: number | null
  githubUrl: string | null
  createdAt: string
  updatedAt: string
  /** When this item last matched its GitHub issue */
  syncedAt: string | null
  /** When it moved to Done (for "completed this week" in reports) */
  doneAt?: string | null
}

export type MilestoneStatus = 'planned' | 'in_progress' | 'delivered'

export interface Milestone {
  id: string
  projectId: string
  title: string
  dueDate: string // YYYY-MM-DD
  status: MilestoneStatus
  notes: string
  /** Linked GitHub milestone number, once synced */
  githubNumber?: number | null
  updatedAt?: string
  syncedAt?: string | null
}

export interface TimeEntry {
  id: string
  projectId: string
  start: string
  /** null while the timer is running */
  end: string | null
  note: string
  workItemId: string | null
}

export interface ChatEntry {
  id: string
  role: 'user' | 'assistant' | 'tool' | 'system' | 'error'
  text: string
  at: string
}

export interface Database {
  version: 1
  customers: Customer[]
  projects: Project[]
  workItems: WorkItem[]
  milestones: Milestone[]
  chats: Record<string, ChatEntry[]>
  timeEntries: TimeEntry[]
  /** Apps linked to the API of another project. */
  links: ProjectLink[]
  /** Per project: Claude Code conversations open in terminals (to reopen after a restart). */
  claudeOpen?: Record<string, OpenClaudeSession[]>
  settings: Settings
}

/** One family from fonts.google.com's catalogue. */
export interface GoogleFontInfo {
  family: string
  category: string
  /** Upright weights the family has, e.g. [400, 700]. */
  weights: number[]
}

export interface Settings {
  /** Shown in customer reports when time is included (optional) */
  hourlyRate?: number | null
  currency?: string
  /** Prettier on save: 'auto' = only in projects that use Prettier */
  formatOnSave?: 'auto' | 'always' | 'off'
  /** 'system' follows the Windows / macOS appearance setting. */
  theme: 'dark' | 'light' | 'system'
  model: string
  projectsRoot: string | null
  /** What the Claude Code button does: carry on with the last conversation (default) or start a new one. */
  claudeStart?: 'continue' | 'new'
  /** Check for and download updates by themselves (default on). Off: only Settings › Check now. */
  autoUpdate?: boolean
  /** A Google Fonts family for the interface; unset = the built-in Inter. */
  uiFont?: string | null
  /** A Google Fonts family for the terminal, editor and code; unset = the built-in JetBrains Mono. */
  monoFont?: string | null
  /** Interface text size: 0.9 Small (the default when unset), 1 Medium, 1.1 Large, 1.25 Larger. */
  uiFontScale?: number
  /** Base weight of interface text (400/500/600); unset = 400. Bold text stays bold. */
  uiFontWeight?: number
  /** Code text size in px for the terminal and editors; unset = 13. */
  monoFontSize?: number
  /** Weight of code text in the terminal and editors (400/500/600); unset = 400. */
  monoFontWeight?: number
  /** Terminal background (#rrggbb); unset = follows the app theme. Text colours switch to suit it. */
  terminalBg?: string | null
  /** Terminal text colour (#rrggbb); unset = the one that suits the background. */
  terminalFg?: string | null
  /** Interface background (#rrggbb); unset = the theme's. Panels and borders are mixed from it. */
  uiBg?: string | null
  /** Interface text colour (#rrggbb); unset = the one that suits the background. */
  uiFg?: string | null
  /** One-click prompts in the Terminal (defaults are used when unset). */
  quickPrompts?: QuickPrompt[]
}

export interface QuickPrompt {
  id: string
  label: string
  text: string
}

/** An app (consumer) that uses the API of another project (provider). */
export interface ProjectLink {
  id: string
  /** The app that calls the API, e.g. the mobile app. */
  consumerId: string
  /** The project that provides the API, e.g. the web app. */
  providerId: string
  /** Files in the provider that define its public API (git pathspecs; globs like backend/** work). */
  apiPaths: string[]
  /** The setting in the consumer that holds the provider's address, e.g. EXPO_PUBLIC_API_URL. */
  envVar?: string
  /** The provider commit the consumer was last updated for. */
  syncedCommit?: string | null
  syncedAt?: string | null
}

export interface LinkStatus {
  linkId: string
  providerHead: string | null
  /** API commits since the consumer was last updated. */
  commits: GitCommit[]
  /** API files edited but not committed yet. */
  uncommitted: string[]
  error?: string
}

/** A snapshot of the project's files taken before Claude worked (for undo). */
export interface Checkpoint {
  id: string
  commit: string
  tree: string
  label: string
  at: string
}

export interface CheckpointChange {
  path: string
  status: 'added' | 'modified' | 'deleted'
}

/** A past Claude Code conversation in a project folder. */
export interface ClaudeSession {
  id: string
  title: string | null
  firstPrompt: string | null
  prompts: number
  /** When the last message was written. */
  updatedAt: string
  sizeKb: number
  /** Started in VS Code or another editor, not in a terminal (Vibeloft's or your own). */
  fromEditor?: boolean
}

export interface RepoInfo {
  lastCommit: string | null
  branch: string | null
  dirty: boolean
}

/** A repo's collaborators (role: read, triage, write, maintain, admin) and pending invites */
export interface GhTeam {
  members: { login: string; role: string }[]
  invited: string[]
}

export interface GhRepo {
  nameWithOwner: string
  description: string
  isPrivate: boolean
  updatedAt: string
}

export interface SyncResult {
  pulled: number
  created: number
  updated: number
  /** Milestones imported, created or updated on GitHub */
  milestones: number
  errors: string[]
}

export type ChatMode = 'plan' | 'build'

export interface PermissionRequest {
  requestId: string
  projectId: string
  toolName: string
  input: Record<string, unknown>
}

export type ChatEvent =
  | { projectId: string; type: 'entry'; entry: ChatEntry }
  | { projectId: string; type: 'delta'; text: string }
  | { projectId: string; type: 'done'; costUsd?: number }
  | { projectId: string; type: 'permission'; request: PermissionRequest }

export interface TerminalInfo {
  id: string
  projectId: string
  title: string
  command: string | null
  exited: boolean
  /** The Claude Code conversation this terminal is in, once known. */
  sessionId?: string
  /** That conversation's name (shown when you hover the tab). */
  conversation?: string
  /** Claude Code ended in this tab (/exit…); what's left is a plain shell. */
  claudeEnded?: boolean
}

/** The setup check: tools Vibeloft needs. */
export type SetupStep = 'claude' | 'git' | 'gh' | 'ghLogin'

export interface SetupStatus {
  platform: string
  claude: { installed: boolean; version: string | null }
  claudeSignedIn: boolean
  claudeAccount: string | null
  git: { installed: boolean; version: string | null }
  gh: { installed: boolean; version: string | null }
  ghSignedIn: boolean
  ghUser: string | null
  /** Windows Package Manager available (used to install Git and the GitHub CLI). */
  winget: boolean
  /** Homebrew available (macOS). */
  brew: boolean
}

/** Automatic updates (installed app only). */
export interface UpdateStatus {
  state: 'dev' | 'idle' | 'checking' | 'downloading' | 'ready' | 'latest' | 'error'
  current: string
  available?: string
  percent?: number
  message?: string
  checkedAt?: string
}

/** A Claude Code hook event reported back from a terminal (see main/hooks.ts). */
export interface ClaudeHookEvent {
  terminalId: string
  event: 'SessionStart' | 'UserPromptSubmit' | 'Notification' | 'Stop' | 'StopFailure' | 'SessionEnd' | 'PreToolUse'
  sessionId?: string
  /** SessionEnd: why Claude Code ended (clear, logout, prompt_input_exit, other…). */
  reason?: string
  /** StopFailure: why the turn ended (rate_limit, authentication_failed, billing_error, server_error, …). */
  error?: string
  /** StopFailure: the error as Claude Code showed it. */
  errorDetails?: string
  prompt?: string
  message?: string
  notificationType?: string
  /** UserPromptSubmit: the undo checkpoint saved before Claude started. */
  checkpoint?: string
}

/** Claude Code usage over a period. Cost is at Anthropic's API prices. */
export interface UsageTotals {
  costUsd: number
  inputTokens: number
  outputTokens: number
  cacheReadTokens: number
  cacheWriteTokens: number
  /** Claude's replies. */
  replies: number
  conversations: number
}

/** Claude Code usage in a project: totals per period, per day (last 30 days), per model. */
export interface ClaudeUsage {
  today: UsageTotals
  week: UsageTotals
  month: UsageTotals
  all: UsageTotals
  days: { date: string; costUsd: number; tokens: number; replies: number }[]
  byModel: { model: string; costUsd: number }[]
  /** Part of the all-time cost from conversations started in VS Code. */
  editorShareUsd: number
}

